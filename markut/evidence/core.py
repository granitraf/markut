def row_units(label: str, group: str, value: str, table_units: str) -> tuple:
    """PURE. (units label, scale word to append to the value or None) from
    the ROW's type, not the table's caption: per-share rows are per share,
    percentages percent, a label's own '(in thousands)' wins, prices are per
    unit, counts are counts; only money rows inherit 'in millions'."""
    text = f"{label} {group}"
    v = (value or "").strip()
    if _PER_SHARE_RE.search(text):
        return "per share", None
    if "%" in v or re.search(r"(?i)percent(?:age)?\b|\bmargin %", label):
        return "percent", None
    own = _LABEL_SCALE_RE.search(label)
    if own:
        noun = (own.group(2) or "").strip() or (_COUNT_NOUN_RE.search(label).group(1).lower() if _COUNT_NOUN_RE.search(label) else "")
        return (f"{_UNIT_WORD.get(own.group(1).lower(), own.group(1).lower())} {noun}".strip(), None)
    if _PER_UNIT_RE.search(label):
        return "per unit", None
    if (_COUNT_RE.search(label) or re.search(r"(?i)\bnumber of\b|restaurants|stores|locations|employees|headcount", group or "")) and "$" not in v:
        return "count", None                      # "Number of company-owned restaurants:" heads a count (2026-10-11)
    if table_units and ("$" in v or re.match(r"^\(?[\d,]+(?:\.\d+)?\)?$", v)):
        return table_units, _UNIT_WORD.get(table_units, table_units)
    return (table_units or "as printed"), None


def _fmt_value(value: str, units: str, label: str) -> str:
    v = (value or "").strip()
    if not v or not units or "%" in v or re.search(r"(?i)per share|per unit|ratio|rate|margin|weeks|count|number of|days|restaurants|stores|locations|"
                                                      r"\((?:kbd|koebd|kboed|mboe|bcf|mcf|bbl|tons?|tonnes|units|x)\)|per day|barrels|\bboe\b|employees|headcount", label):
        return v
    if "$" in v or re.match(r"^\(?[\d,]+(?:\.\d+)?\)?$", v):
        return f"{v} {_UNIT_WORD.get(units, units)}"
    return v


def _entity_key(cell: dict) -> str:
    # the column's thing, ignoring amount/percent markers and period words
    e = (cell.get("entity") or "").lower()
    e = re.sub(r"(?i)amount|percent(?:age)? of (?:total )?(?:revenues?|sales)|% of (?:revenues?|sales)|as a percentage of", "", e)
    return re.sub(r"\s+", " ", e).strip()


_MONTHS = {m: i for i, m in enumerate(("jan", "feb", "mar", "apr", "may", "jun", "jul", "aug", "sep", "oct", "nov", "dec"), 1)}


def _pair_cells(cells: list, prefer_percent: bool = False, entity: str = None):
    """(current, year_ago) cells: the shortest period class present, the same
    column entity (a brand or segment column never pairs with its neighbour),
    amount columns unless percent-of-revenue columns are asked for, ordered by
    date. entity=None means the consolidated / Total column when the table has
    entity columns, else whatever column there is."""
    # a "Change" column holds a difference, never a figure (2026-10-11: a bank's quarterly trends)
    classes = [c for c in cells if c.get("period") and c["period"] not in ("", "unstated", "change")]
    if not classes:
        # no level column: an undated one, else the stated change itself (a
        # filer that publishes a volume only as "+5%"); figure_line says so
        rest = [c for c in cells if c.get("period") != "change"] or [c for c in cells if c.get("period") == "change"]
        return (rest[0] if rest else None), None
    order = {"quarter": 0, "YTD (H1)": 1, "YTD (9M)": 2, "annual": 3, "ttm": 4}
    def rank(c):
        p = c["period"]
        return order.get(p, 5 if p.startswith("period ended") else 6)
    best = min(rank(c) for c in classes)
    same = [c for c in classes if rank(c) == best]
    pct = [c for c in same if PERCENT_COL_RE.search(c.get("entity", ""))]
    amount = [c for c in same if c not in pct]
    use = (pct or amount) if prefer_percent else (amount or same)
    keys = {_entity_key(c) for c in use}
    if entity is not None:
        use = [c for c in use if _entity_key(c) == entity.lower()] or use
    elif len(keys) > 1:
        tot = [c for c in use if re.search(r"(?i)^total|consolidated|^company", _entity_key(c))]
        # the column kind with the most columns: a convenience translation
        # ("US$" beside two "RMB" columns, 2026-10-11) is one column; ties
        # keep the old rule (the shortest name)
        n = {k_: sum(1 for c in use if _entity_key(c) == k_) for k_ in keys}
        # the reported figure first; an adjusted, constant-currency or
        # reconciling column ("Impact from …") last; then the most columns,
        # the shortest name — and a fixed order, so a tie is never decided by
        # set order (2026-10-11: the same filing read differently run to run)
        alt = lambda k_: bool(re.search(r"(?i)adjusted|non-?gaap|\bcer\b|constant currency|organic|pro forma|impact|adjustments?\b|"
                                        r"effect of|excluding|reconcil", k_))
        reported = lambda k_: bool(re.search(r"(?i)\breported\b|(?<!non-)\bgaap\b", k_)) and not alt(k_)
        main = max(sorted(keys, key=lambda k_: (len(k_), k_)), key=lambda k_: (reported(k_), not alt(k_), n[k_]))
        use = tot or [c for c in use if _entity_key(c) == main]
    def when(c):
        # (year, month, day) of the column's end date; (year, 0, 0) when only a
        # year is printed; None when no date at all
        d = period_from_heading(c.get("heading", "")).get("ended") or ""
        m = re.search(r"([A-Za-z]{3,9})\.?\s+(\d{1,2}),?\s+(\d{4})", d)
        if m and m.group(1)[:3].lower() in _MONTHS:
            return (int(m.group(3)), _MONTHS[m.group(1)[:3].lower()], int(m.group(2)))
        y = re.search(r"(\d{4})", d)
        return (int(y.group(1)), 0, 0) if y else None
    def key(c):
        w = when(c)
        return (-w[0], -w[1], -w[2]) if w else (0, 0, 0)
    use = sorted(use, key=key)
    cur = use[0] if use else None
    same = [c for c in use[1:] if cur and _entity_key(c) == _entity_key(cur)]
    # the comparison is the YEAR-AGO column: run #28 (TSM "2Q26 | 2Q25 | 1Q26")
    # — the next column over can be the previous quarter
    wc = when(cur) if cur else None
    year_ago = [c for c in same if wc and when(c) and when(c)[0] == wc[0] - 1 and (not wc[1] or abs(when(c)[1] - wc[1]) <= 1)]
    if wc is None and len(same) > 1:
        # several undated columns of one kind: which is "year-ago" is a guess
        # (2026-10-11: consecutive quarters were paired 1Q against 2Q)
        return cur, None
    prev = (year_ago or [c for c in same if not (wc and when(c) and when(c)[0] == wc[0])] or same or [None])[0]
    return cur, prev


def _col_date(cell: dict):
    """(year, month) of a column's end date: a printed date, else a compact
    quarter label ("Q2 2026", "2Q26"); None when the heading names neither."""
    if not cell:
        return None
    d = period_from_heading(cell.get("heading", "")).get("ended") or ""
    m = re.search(r"([A-Za-z]{3,9})\.?\s+\d{1,2},?\s+(\d{4})", d)
    if m and m.group(1)[:3].lower() in _MONTHS:
        return int(m.group(2)), _MONTHS[m.group(1)[:3].lower()]
    y = re.search(r"\b(\d{4})\b", d)
    return (int(y.group(1)), 0) if y else None


def _stale(cur: dict, src: dict) -> bool:
    """A "current" figure dated more than seven months before the document it
    comes from was misread — a 10-Q filed in August has no current quarter
    ending the year before (2026-10-11). Undated figures are not judged."""
    d, f = _col_date(cur), re.match(r"(\d{4})-(\d{2})", (src or {}).get("filing_date") or "")
    if not d or not f or not d[1]:
        return False
    return (int(f.group(1)) * 12 + int(f.group(2))) - (d[0] * 12 + d[1]) > 7


def _change(cur, prev):
    a, b = num_of(cur), num_of(prev)
    if a is None or b is None or b == 0:
        return ""
    if "%" in (cur or "") and "%" in (prev or ""):
        return f"{a - b:+.1f} pts (DERIVED: {a:g}% − {b:g}%)"
    return f"{(a / b - 1) * 100:+.1f}% (DERIVED: {cur.strip()} / {prev.strip()} − 1)"


def _source(src: dict, rec: dict) -> str:
    # one short tag per table; the legend under the block header spells it out
    key = (src["form"], src["name"], rec.get("caption", ""), src["filing_date"])
    if key not in _LEGEND:
        _LEGEND[key] = f"T{len(_LEGEND) + 1}"
    return f"[source: {_LEGEND[key]}]"


def legend_lines() -> list:
    return [f"  {tag} = EDGAR/{form} {name}" + (f' "{cap}"' if cap else "") + f", filed {date}"
            for (form, name, cap, date), tag in _LEGEND.items()]


def _period_text(cell: dict, src: dict) -> str:
    p = cell.get("period") or "unstated"
    if p.startswith("period ended") and src.get("headline_period"):
        p = f"{src['headline_period']} ({p}; duration from the release headline)"
    head = re.sub(r"(?i)\b(?:amount|percent(?:age)? of (?:total )?(?:revenues?|sales))\b", "", cell.get("heading", "")).strip(" ,;")
    head = re.sub(r"\s+", " ", head)
    return f"{p}, {head}" if head and head.lower() not in p.lower() else p


def _currency(rec: dict, cell: dict = None) -> str:
    """The ISO currency of a figure: its table's caption, else its column
    heading ("As of June 30, 2026 RMB (in millions)", 2026-10-11)."""
    return rec.get("currency") or caption_currency((cell or {}).get("heading", ""))


def _as_shown(value: str, rec: dict, cell: dict = None) -> str:
    """A foreign filer's '$' is its own currency (TSM's 'NT$' prints as '$'):
    the line names the currency, so the sign is dropped (run #28 rule)."""
    v = (value or "").strip()
    ccy = _currency(rec, cell)
    return re.sub(r"\$\s?", "", v).strip() if ccy and ccy != "USD" else v


def _scaled(value: str, scale) -> str:
    v = (value or "").strip()
    return f"{v} {scale}" if scale and v else v


def figure_line(label: str, rec: dict, cur: dict, prev, src: dict, segment: str, basis: str, kind: str = "") -> str:
    # P0 (run #26): units come from the row type ("$2.02 million" was a
    # per-share figure that inherited the table's "in millions")
    units, scale = row_units(label, rec.get("group", ""), cur.get("value", ""), rec.get("units", ""))
    if cur.get("period") == "change":
        # a stated change is never scaled to the table's millions (2026-10-11)
        units, scale = ("percent change" if "%" in (cur.get("value") or "") else "change, as printed"), None
    ccy = _currency(rec, cur)
    if ccy and ccy != "USD" and units and units not in ("percent", "count", "as printed", "percent change", "change, as printed"):
        units = f"{ccy} {units}"      # run #28: 'TWD millions', 'TWD per share' — never an unlabelled foreign amount
    units = _units_label(units, rec)
    cur_v = _scaled(_as_shown(cur["value"], rec, cur), scale)
    if prev is not None:
        prev_v = _scaled(_as_shown(prev["value"], rec, cur), scale)
        change = _change(_as_shown(cur["value"], rec, cur), _as_shown(prev["value"], rec, cur))
        prev_p = _period_text(prev, src)
        if prev.get("period") == cur.get("period"):
            d = period_from_heading(prev.get("heading", "")).get("ended")
            prev_p = d or prev_p
        # "year-ago" only when the dates say so: a table of the latest two
        # quarters compares with the prior quarter (2026-10-11, pre-existing)
        a, b = _col_date(cur), _col_date(prev)
        which = "prior period" if a and b and not (a[0] - b[0] == 1 and (not a[1] or not b[1] or abs(a[1] - b[1]) <= 1)) else "year-ago"
        body = f"{cur_v} ({_period_text(cur, src)}) vs {prev_v} {which} ({prev_p})" + (f"; change {change}" if change else "")
    elif cur.get("period") == "change":
        body = f"{cur_v} ({_period_text(cur, src)}); a stated change — the table prints no level"
    else:
        body = f"{cur_v} ({_period_text(cur, src)}); no year-ago column in this table"
    grp = f" [{rec['group']}]" if rec.get("group") and rec["group"].lower() not in label.lower() else ""
    kind_t = f"{kind}: " if kind and label_matches(label, kind.replace("KPI ", "")) < 0.9 else ("" if not kind.startswith("KPI ") else f"{kind}: ")
    return (f"- {kind_t}{label}{grp}: {body}  ({units or 'as printed'}; {basis}; {segment})  {_source(src, rec)}")


def balance_line(label: str, rec: dict, cur: dict, prev, src: dict) -> str:
    """A point-in-time balance (run #26, P2 item 7): dated "as of", never a
    duration and never "year-ago" — the comparison column of a balance sheet
    is the earlier balance-sheet date, often the fiscal year-end."""
    units, scale = row_units(label, rec.get("group", ""), cur.get("value", ""), rec.get("units", ""))
    ccy = _currency(rec, cur)
    if ccy and ccy != "USD" and units and units not in ("percent", "count", "as printed"):
        units = f"{ccy} {units}"      # as figure_line: a foreign amount always names its currency
    units = _units_label(units, rec)
    def at(c):
        return period_from_heading(c.get("heading", "")).get("ended") or c.get("heading", "") or "date not printed"
    body = f"{_scaled(_as_shown(cur['value'], rec, cur), scale)} as of {at(cur)}"
    if prev is not None:
        body += f" vs {_scaled(_as_shown(prev['value'], rec, cur), scale)} as of {at(prev)}"
    # a total names its own scope; the group above it would mislabel it
    grp = (f" [{rec['group']}]" if rec.get("group") and rec["group"].lower() not in label.lower()
           and not re.match(r"(?i)^total\b", label) else "")
    return f"- {label}{grp}: {body}  ({units or 'as printed'}; {_basis(rec, label)}; point-in-time balance)  {_source(src, rec)}"


def _basis(rec: dict, label: str) -> str:
    text = " ".join([rec.get("caption", ""), rec.get("group", ""), label])
    return "non-GAAP" if NON_GAAP_RE.search(text) else "GAAP"


def _segment_of(text: str, segments: list) -> str:
    low = (text or "").lower()
    for s in segments:
        for a in aliases(s):
            if len(a) <= 6 and re.search(r"\b" + re.escape(a.lower()) + r"\b", low) or (len(a) > 6 and a.lower() in low):
                return s
    return ""


def headline_period(text: str) -> str:
    """PURE. The reporting period a release announces in its first lines:
    'results for the quarter ended June 30, 2026' -> quarter; 'second quarter'
    -> quarter; 'fiscal year' -> annual; 'six months' -> YTD (H1)."""
    head = (text or "")[:700].lower()
    if re.search(r"\b(?:six[- ]month|first half|26 weeks|26-week)\b", head):
        return "YTD (H1)"
    if re.search(r"\b(?:nine[- ]month|39 weeks|39-week)\b", head):
        return "YTD (9M)"
    if re.search(r"\b(?:first|second|third|fourth|q[1-4])\b.{0,20}\bquarter|\bquarter(?:ly)? (?:ended|results|of)|\b13 weeks\b|\bthree months\b", head):
        return "quarter"
    if re.search(r"\b(?:full[- ]year|fiscal year|year ended|annual) (?:results|ended)?", head):
        return "annual"
    return ""


def core_sources(fs: dict) -> list:
    """[{form, name, filing_date, url, html, text, headline_period}] for the
    results release's text exhibits (8-K or 6-K) and the interim report
    (10-Q, or the documents of a 6-K interim report) — each under its REAL
    form (run #28: a 6-K is never labelled 8-K or 10-Q)."""
    from markut.evidence.filers import base_form
    from markut.evidence.sections import _filing_docs, exhibits_of
    out = []
    if fs.get("8-K"):
        for exh in exhibits_of(fs["8-K"]):
            if exh["image_only"]:
                continue
            raw = fetch_filing_html(exh["url"])
            out.append({"form": exh["form"], "name": exh["name"], "filing_date": exh["filing_date"], "url": exh["url"],
                        "html": raw, "text": exh["text"], "headline_period": headline_period(exh["text"])})
    q = fs.get("10-Q")
    if q and base_form(q["form"]) == "6-K":
        for name, text, raw in _filing_docs(q):
            out.append({"form": q["form"], "name": name, "filing_date": q["filing_date"], "url": q["base_url"] + "/" + name,
                        "html": raw, "text": text, "headline_period": headline_period(text) or "quarter"})
    elif q:
        raw = fetch_filing_html(q["url"])
        out.append({"form": q["form"], "name": q.get("primary_doc", q["form"]), "filing_date": q["filing_date"],
                    "url": q["url"], "html": raw, "text": "", "headline_period": "quarter"})
    return out


def _document_scale(records: list, src: dict) -> tuple:
    """(units, whole): the scale every table of one document that states one
    agrees on ('' when they differ or none does); whole=True when the
    document states no scale anywhere — its figures are whole units."""
    stated = {r["units"] for r in records if r.get("units")}
    if len(stated) == 1:
        return next(iter(stated)), False
    if stated:
        return "", False
    from markut.evidence.edgar import _UNITS_RE
    text = src.get("text") or html_to_text(src.get("html") or "")
    return "", not _UNITS_RE.search(text or "")


def _units_label(units: str, rec: dict) -> str:
    """Say where a table's units came from when the table itself is silent."""
    if rec.get("units_inferred") and units not in ("percent", "count", "per share", "per unit") and "per share" not in units:
        return f"{units} — the document's stated scale"
    if rec.get("units_whole") and units == "as printed":
        return "whole units — the document states no scale"
    return units


def classify_tables(records: list) -> dict:
    """{table index: {"income","cash","kpi","segment","percent"}} by caption and row labels."""
    by_table = {}
    for r in records:
        by_table.setdefault(r["table"], []).append(r)
    kinds = {}
    for t, rows in by_table.items():
        labels = [r["label"] for r in rows]
        caption = rows[0].get("caption", "")
        k = set()
        income_hits = sum(1 for lab in labels if any(re.search(p, lab.strip().lower()) for _, p in INCOME_ROWS))
        cash_hits = sum(1 for lab in labels if any(re.search(p, lab.strip().lower()) for _, p in CASH_ROWS))
        # an equity statement repeats "Net income" under its equity columns
        # (TSM's interim 6-K): it is not an income statement
        # equity components as its columns mark one even when the caption does not
        equity_cols = {e for r in rows for c in r["cells"] for e in [c.get("entity", "")]
                       if re.search(r"(?i)capital stock|capital surplus|share premium|retained earnings|unappropriated|treasury (?:stock|shares)|"
                                    r"other equity|non-?controlling interests?|accumulated other comprehensive", e)}
        is_equity = bool(re.search(r"(?i)changes in (?:\w+['’]?\s+)?equity|statements? of (?:\w+['’]?\s+)?equity", caption)) or len(equity_cols) >= 2
        if income_hits >= 2 and not is_equity:
            k.add("income")
        if cash_hits >= 2 or (cash_hits >= 1 and re.search(r"(?i)cash flow", caption)):
            k.add("cash")
        # two balance-sheet totals, or a caption that names the statement
        bal_hits = sum(1 for lab in labels if _BALANCE_TOTAL_RE.search(lab.strip()))
        # the statement's title may sit in the caption, the first header cell
        # ("Selected Consolidated Balance Sheet Information") or a section row
        heads = " ".join([caption] + [str(h) for h in rows[0].get("periods") or []] + sorted({r.get("group", "") for r in rows}))
        # "Balance Sheet Location of Hedged Items" (a hedging note) names a line, not the statement
        named = bool(re.search(r"(?i)balance sheets?(?! (?:location|classification|caption|line))|financial position|financial condition", heads))
        cont = bool(re.search(r"(?i)\(continued\)", heads))
        if (bal_hits >= 2 or named) and not is_equity:
            k.add("balance")
            if named:
                k.add("balance_named")      # titled as the statement itself
            if cont:
                k.add("balance_continued")
        if KPI_TABLE_RE.search(caption) or KPI_TABLE_RE.search(" ".join(r.get("group", "") for r in rows)):
            k.add("kpi")
        if SEGMENT_TABLE_RE.search(caption) or any(SEGMENT_TABLE_RE.search(r.get("group", "")) for r in rows):
            k.add("segment")
        if any(PERCENT_COL_RE.search(c.get("entity", "")) for r in rows for c in r["cells"]):
            k.add("percent")
        kinds[t] = k
    return kinds


def extract_core(fs: dict, profile: dict, plan: dict = None) -> dict:
    """-> {"text": the [CORE FIGURES] section, "kpi_values": {name: bool},
    "lines": [...], "checks": [...]}."""
    profile = profile or {}
    _LEGEND.clear()
    from markut.evidence.filers import source_phrase
    _SRC = source_phrase(fs)   # run #28: name the forms this company files
    segments = [s.get("name", "") for s in profile.get("segments", []) if isinstance(s, dict) and s.get("name")]
    kpi_names = [k.get("name", "") for k in profile.get("company_kpis", []) if isinstance(k, dict) and k.get("name")]
    for q in (plan or {}).get("key_questions", []):
        for k in q.get("kpis") or []:
            if isinstance(k, str) and k.strip() and all(label_matches(k, n) < 0.6 for n in kpi_names):
                kpi_names.append(k.strip())
    blocks = {"income": [], "kpi": [], "segment": [], "cash": [], "derived": [], "pct": [], "lease": [], "balance": []}
    seen = set()
    all_records = []          # (src, rec)
    balance_cands = []        # (src, rec, cur, prev, label shown, is debt) — one balance sheet is kept after the loop
    lease_cands = []          # lease balances — the latest date of each line is kept after the loop
    income_cands = []         # (priority, period rank, order, line) — the cap applies after ordering
    prior_label = {}          # the row above, per table
    for src in core_sources(fs):
        try:
            records = parse_tables(src["html"])
        except Exception as e:
            blocks["income"].append(f"- [table parsing failed for {src['form']} {src['name']}: {e}]")
            continue
        kinds = classify_tables(records)
        # units a table leaves unstated (2026-10-11): the document's one stated
        # scale when every table that states one agrees; "whole units" when the
        # document states none anywhere (a small filer reporting in dollars)
        doc_units, whole = _document_scale(records, src)
        for r in records:
            if not r.get("units"):
                if doc_units:
                    r["units"], r["units_inferred"] = doc_units, True
                elif whole:
                    r["units_whole"] = True
        # a row with no section heading takes its scope from the subtotal under
        # it ("Borrowings" above "Total non-current liabilities"), so a label a
        # statement repeats (non-current, then current) is told apart
        scope, nxt = {}, {}
        for r in reversed(records):
            m = re.match(r"(?i)^total ((?:non-?current |current )(?:assets|liabilities))\b", r["label"].strip())
            if m:
                nxt[r["table"]] = m.group(1).lower()
            elif re.match(r"(?i)^total\b", r["label"].strip()):
                nxt.pop(r["table"], None)
            scope[id(r)] = nxt.get(r["table"], "")
        for rec in records:
            all_records.append((src, rec))
            prior, prior_label[(src["name"], rec["table"])] = prior_label.get((src["name"], rec["table"]), ""), rec["label"]
            if BOILERPLATE_LABEL_RE.search(rec["label"]):
                continue
            k = kinds.get(rec["table"], set())
            label = rec["label"]
            low = label.strip().lower()
            cur, prev = _pair_cells(rec["cells"])
            if cur is None or num_of(cur["value"]) is None or _stale(cur, src):
                continue
            # a balance needs a dated column: a maturity table's "Less Than 1
            # Year" / "5-10 Years" columns are a schedule (run #28, TSM)
            # a balance is dated and is not a duration: a quarter's "Interest on
            # lease liabilities" is a cost (2026-10-11), an average is not a balance
            flow = cur.get("period") in ("quarter", "YTD (H1)", "YTD (9M)", "annual", "ttm")
            if LEASE_ROW_RE.search(label) and not _LEASE_SKIP_RE.search(label) and \
                    (flow or not period_from_heading(cur.get("heading", "")).get("ended")):
                continue
            if LEASE_ROW_RE.search(label) and not _LEASE_SKIP_RE.search(label):
                lease_cands.append((_ended_key(cur) or (0, 0, 0), len(lease_cands), low, rec.get("group", ""), label, rec, cur, prev, src))
                continue
            bal = balance_row(label, prior) if "balance" in k else None
            if bal and period_from_heading(cur.get("heading", "")).get("ended"):
                clean = _NOTE_REF_RE.sub("", label).strip()          # "(Note 6)" names a note, not the line
                shown = clean if bal[0] != "Total assets" or low.startswith("total assets") else f"Total assets (printed as {clean})"
                if not rec.get("group") and scope.get(id(rec)):
                    rec = dict(rec, group=scope[id(rec)])
                balance_cands.append((src, rec, cur, prev, shown, bal, ("balance_named" in k, "balance_continued" in k)))
                continue
            # entity tables (a column per segment / brand): one line per matching entity for revenue-type rows
            entity_cells = [c for c in rec["cells"] if c.get("entity") and _segment_of(c["entity"], segments)]
            if entity_cells and SEGMENT_ROW_RE.search(label) and not re.search(r"(?i)cost|expense", label):
                for c in entity_cells:
                    ent = _segment_of(c["entity"], segments)
                    cur_e, prev_e = _pair_cells(rec["cells"], entity=_entity_key(c))
                    key = ("seg", label, ent, c["period"])
                    if key in seen or len(blocks["segment"]) >= MAX_LINES["segment"] or cur_e is None:
                        continue
                    seen.add(key)
                    blocks["segment"].append(figure_line(label, rec, cur_e, prev_e, src, ent, _basis(rec, label), ""))
            if entity_cells and not re.search(r"(?i)^total|consolidated|^company", _entity_key(cur)):
                continue      # a brand/segment column value is not a consolidated figure
            seg_label = _segment_of(" ".join([rec.get("group", ""), label]), segments)
            seg = seg_label or "company-wide"
            basis = _basis(rec, label)
            placed = False
            # what the row measures: its section heading, else the table's caption
            # ("Segment Revenue Constant Currency Reconciliation", 2026-10-11)
            if seg_label and (SEGMENT_ROW_RE.search(label) or re.search(r"(?i)revenue|sales|income|profit", rec.get("group") or rec.get("caption", ""))) \
                    and not re.search(r"(?i)cost|expense", label + " " + rec.get("group", "")):
                key = ("seg", label, seg, cur["period"])
                if key not in seen and len(blocks["segment"]) < MAX_LINES["segment"]:
                    seen.add(key)
                    blocks["segment"].append(figure_line(label, rec, cur, prev, src, seg, basis, ""))
                continue
            for name, pat in INCOME_ROWS:
                if re.search(pat, low) and ("income" in k or "kpi" in k):
                    key = ("inc", name, seg, cur["period"], basis)
                    if key not in seen:
                        seen.add(key)
                        income_cands.append((INCOME_PRIORITY.get(name, 9), _PERIOD_RANK.get(cur.get("period"), 5), len(income_cands),
                                             figure_line(label, rec, cur, prev, src, seg, basis, name if name.lower() != low else ""),
                                             (name, seg, basis, num_of(cur["value"]))))
                    placed = True
                    break
            if not placed:
                for name, pat in CASH_ROWS:
                    hit = re.search(pat, low) or (name == "Capital expenditures" and _is_capex(rec))
                    if hit and len(blocks["cash"]) < MAX_LINES["cash"]:
                        key = ("cash", name, cur["period"])
                        if key not in seen:
                            seen.add(key)
                            blocks["cash"].append(figure_line(label, rec, cur, prev, src, seg, basis, name if name.lower() != low else ""))
                        placed = True
                        break
            if not placed and "kpi" in k and len(blocks["kpi"]) < MAX_LINES["kpi"]:
                key = ("kpi", low, rec.get("group", ""), cur["period"])
                if key not in seen:
                    seen.add(key)
                    blocks["kpi"].append(figure_line(label, rec, cur, prev, src, seg, "company-defined", ""))
                placed = True
            # run #26 (P1): every percentage row (margin by segment or line,
            # current vs year-ago) — not just the total line
            # ownership tables (a subsidiary's "Percentage of Ownership") are
            # not performance figures (run #28, TSM's interim statements)
            if re.search(r"(?i)ownership|voting|subsidiar|interest held|shareholding",
                         " ".join([rec.get("caption", "")] + [c.get("heading", "") for c in rec["cells"]])):
                continue
            # percentages from performance tables only (income / segment / KPI /
            # percent-of-revenue) or rows that name a margin or a growth rate:
            # a compensation note's "Risk-free interest rate 1.40%" is a model
            # assumption, not a result (run #28, TSM's interim statements)
            performance = bool(k & {"income", "segment", "kpi", "percent"}) or re.search(
                r"(?i)margin|growth|percentage of (?:total |net )?(?:sales|revenues?)|% of (?:sales|revenues?)", label + " " + rec.get("group", ""))
            if not placed and "%" not in (cur.get("value") or "") and any("%" in (c.get("value") or "") for c in rec["cells"]):
                # amounts beside a growth-rate column (MSFT's segment table): the
                # percentage line pairs the percentage cells (2026-10-11)
                pcur, pprev = _pair_cells([c for c in rec["cells"] if "%" in (c.get("value") or "") and c.get("period") != "change"])
                if pcur is not None:
                    cur, prev = pcur, pprev
            if not placed and performance and "%" in (cur.get("value") or "") and len(blocks["pct"]) < MAX_LINES["pct"]:
                key = ("pct", low, rec.get("group", ""), cur["period"])
                if key not in seen:
                    seen.add(key)
                    blocks["pct"].append(figure_line(label, rec, cur, prev, src, seg, basis, ""))

    # the key lines first when the summary is full (2026-10-11: new pre-tax and
    # bank rows crowded a company's revenue out of a first-come list)
    # the same figure from several tables is one fact: keep the copy with a
    # year-ago comparison, else a dated one (2026-10-11: one report printed its
    # quarter's sales in three tables and net income fell off the summary)
    best = {}
    for c in income_cands:
        fact, has_ago = c[4], " year-ago (" in c[3]
        score = (has_ago, c[1] < 5, -c[2])
        if fact not in best or score > best[fact][0]:
            best[fact] = (score, c)
    kept = sorted(c for _, c in best.values())
    blocks["income"] += [c[3] for c in kept][:max(0, MAX_LINES["income"] - len(blocks["income"]))]
    blocks["balance"], debt_rows = pick_balance_sheet(balance_cands)
    # the latest date of each lease line first, once (2026-10-11: AMZN's note
    # in one table per date kept the older one and the cap cut the newer)
    for _, _, low, grp, label, rec, cur, prev, src in sorted(lease_cands, key=lambda c: (tuple(-x for x in c[0]), c[1])):
        key = ("lease", low, grp.lower())
        if key not in seen and len(blocks["lease"]) < MAX_LINES["lease"]:
            seen.add(key)
            blocks["lease"].append(balance_line(label, rec, cur, prev, src))

    # KPI values for every profiled (and planner-linked) KPI. P0 (run #26):
    # "iPhone net sales" resolved to Total net sales because word overlap
    # was the only test. A KPI must now be matched by a row that names what
    # the KPI names — its segment / product (never a company total), or its
    # distinctive words — and a grouping KPI ("net sales by segment") is
    # satisfied by the parsed segment lines. A wrong value is worse than none.
    derived, seen_d = [], set()
    for ln in derived_lines(all_records, segments):
        # one line per (metric, value, period): the same margin computed from
        # two tables of the same release is one fact
        m = re.match(r"^- (DERIVED [A-Za-z ]+?|SANITY CHECK [a-z ]+?)(?: OK| MISMATCH[^:]*)?: ([-\d.,]+%?)", ln)
        per = re.search(r"\((quarter|YTD \(H1\)|YTD \(9M\)|annual|ttm)[;)]", ln)
        key = (m.group(1), m.group(2), per.group(1) if per else "") if m else re.sub(r"\s*\[source:.*$", "", ln)[:120]
        if key not in seen_d:
            seen_d.add(key); derived.append(ln)
    blocks["derived"] = derived
    kpi_lines, kpi_values = [], {}
    seg_rows = blocks["segment"]
    for name in kpi_names:
        if GROUPING_KPI_RE.search(name):
            if seg_rows:
                shown = [re.match(r"^- ([^:\[]+)", l).group(1).strip() for l in seg_rows if re.match(r"^- ([^:\[]+)", l)]
                uniq = list(dict.fromkeys(shown))
                kpi_lines.append(f"- KPI {name}: shown as {len(seg_rows)} segment lines above ({', '.join(uniq[:12])}"
                                 + (f", … {len(uniq) - 12} more" if len(uniq) > 12 else "") + ")")
                kpi_values[name] = True
            else:
                kpi_lines.append(f"- KPI value not found: {name} (no segment or revenue-line table in {_SRC})")
                kpi_values[name] = False
            continue
        # a company-defined measure ("Cash Capex, non-GAAP", "…excluding margin
        # postings") is the company's own row when it prints one; a plain one
        # takes the cash-flow statement's line (2026-10-11)
        own = bool(NON_GAAP_RE.search(name) or re.search(r"(?i)\bcash cap", name))
        found = resolve_kpi(name, all_records, segments) if own else None
        cash_line = None if found else _cash_kpi_line(name, blocks["cash"])
        if not found and not cash_line and not own:
            found = resolve_kpi(name, all_records, segments)
        if cash_line:
            # run #29: a cash-flow metric is the cash-flow summary's own line
            # (capex can sit under an "Acquisitions of:" heading no label names)
            kpi_lines.append(cash_line)
            kpi_values[name] = True
        elif found:
            src, rec, cur, prev, note = found
            seg = _segment_of(" ".join([rec.get("group", ""), rec["label"], cur.get("entity", "")]), segments) or "company-wide"
            if is_balance_kpi(name):
                # a balance is dated "as of", never "vs year-ago"
                line = balance_line(rec["label"], rec, cur, prev, src).replace("- ", f"- KPI {name}: ", 1)
            else:
                line = figure_line(rec["label"], rec, cur, prev, src, seg, "company-defined", f"KPI {name}")
            kpi_lines.append(line.replace("  [source:", f"  ({note})  [source:", 1) if note else line)
            kpi_values[name] = True
        elif _derived_kpi(name, derived, segments):
            kpi_lines.append(_derived_kpi(name, derived, segments))
            kpi_values[name] = True
        else:
            kpi_lines.append(f"- KPI value not found: {name} (no table row in {_SRC} names this metric)")
            kpi_values[name] = False
    lines = [f"[CORE FIGURES] (extracted by code from the tables of {_SRC} before any question was asked; "
             "each line: figure (period) vs year-ago (or 'prior period' where the table prints no year-ago column); change — "
             "then (units; basis; segment) and its source table; "
             "'KPI value not found' means the metric was not in a table, not that it does not exist)"]
    for title, key in (("Income statement summary", "income"), ("KPI / operating metrics table", "kpi"),
                       ("Segment and revenue lines", "segment"), ("Percentage tables (each line with its comparison column)", "pct"),
                       ("Cash flow summary", "cash")):
        lines.append(f"-- {title} --")
        lines.extend(blocks[key] or [f"- none found by table structure in {_SRC}"])
    lines.append("-- Balance sheet summary --")
    lines.extend((blocks["balance"] + total_debt_line(debt_rows)) or [f"- none found by table structure in {_SRC}"])
    lines.append("-- Lease liabilities (balance sheet or lease note) --")
    lines.extend(blocks["lease"] or [f"- no lease-liability row in {_SRC} tables"])
    lines.append("-- KPI values for the profiled metrics --")
    lines.extend(kpi_lines or ["- the profile listed no KPIs"])
    lines.append("-- Derived metrics and sanity checks (computed in code) --")
    lines.extend(blocks["derived"] or ["- no derivable pairs found"])
    if _LEGEND:
        lines.append("-- Source tables --")
        lines.extend(legend_lines())
    return {"text": "\n".join(lines), "kpi_values": kpi_values, "lines": lines,
            "checks": [l for l in blocks["derived"] if "SANITY" in l]}


def _ended_key(cell: dict):
    """(year, month, day) of a balance column's date; None when undated."""
    d = period_from_heading((cell or {}).get("heading", "")).get("ended") or ""
    m = re.search(r"([A-Za-z]{3,9})\.?\s+(\d{1,2}),?\s+(\d{4})", d)
    if m and m.group(1)[:3].lower() in _MONTHS:
        return int(m.group(3)), _MONTHS[m.group(1)[:3].lower()], int(m.group(2))
    return None


def pick_balance_sheet(cands: list) -> tuple:
    """-> (balance lines, debt rows) from ONE balance sheet: the source
    document with the latest balance-sheet date, the fuller one on a tie.
    2026-10-11: a stale first-quarter release beside the second-quarter
    10-Q put two dates in one summary, and the total debt took the old one."""
    by = {}
    for c in cands:
        when = _ended_key(c[2])
        if when:
            by.setdefault((c[0]["name"], when), []).append(c)
    if not by:
        return [], []
    best = max(by, key=lambda k: (k[1], len(by[k])))
    rows = by[best]
    # one statement: a filing holds many balance-type tables (a bank's
    # derivatives and parent-only tables, a segment's totals, a hedging note) —
    # keep the best table (titled as the statement first, then the most rows)
    # and the "(continued)" tables chained to it, nothing else
    tables = {}
    for c in rows:
        tables.setdefault(c[1]["table"], []).append(c)
    order = sorted(tables)
    flags = {t: tables[t][0][6] for t in order}
    top = max(order, key=lambda t: (flags[t][0], len(tables[t])))
    keep, i = [top], order.index(top)
    # debt and securities rows sit in both halves (current / non-current)
    kinds = lambda t: {c[5][0] for c in tables[t]} - {"Debt", "Marketable securities"}
    def joins(a, b):
        # one table continues the other: the later one titled "(continued)", or
        # the very next table holding the other half of the statement (one
        # filer prints assets, then liabilities and equity under a page header) — a
        # table that repeats a kind of line already kept (a segment's "Total
        # assets") is not part of it
        first, later = min(a, b), max(a, b)
        covered = set().union(*(kinds(t) for t in keep))
        return (flags[later][1] and flags[first][0]) or (abs(a - b) == 1 and not (kinds(b) & covered))
    while i > 0 and joins(order[i], order[i - 1]):
        i -= 1
        keep.insert(0, order[i])
    j = order.index(top)
    while j + 1 < len(order) and joins(order[j], order[j + 1]):
        j += 1
        keep.append(order[j])
    rows = [c for t in keep for c in tables[t]]
    lines, debt, seen = [], [], set()
    for src, rec, cur, prev, shown, (name, is_debt), _ in rows:
        # one fact once: the same kind of line with the same value (a statement
        # and its summary repeat it); current and non-current term debt differ
        key = (name, num_of(cur["value"]))
        if key in seen or len(lines) >= MAX_LINES["balance"]:
            continue
        seen.add(key)
        lines.append(balance_line(shown, rec, cur, prev, src))
        if is_debt:
            debt.append((src, rec, cur, shown))
    return lines, debt


def total_debt_line(debt_rows: list) -> list:
    """The debt rows of one balance sheet, summed, every row named — the rows
    of the first table with debt, at its latest date; leases are excluded
    (they have their own block). [] when there is nothing to add."""
    if not debt_rows:
        return []
    src0, rec0, cur0, _ = debt_rows[0]
    # every debt row of the one statement kept — both halves when it spans two
    # tables (a "(continued)" page holds the non-current debt, 2026-10-11)
    rows = [(src, rec, cur, shown) for src, rec, cur, shown in debt_rows
            if src["name"] == src0["name"] and _ended_key(cur) == _ended_key(cur0)]
    vals = [num_of(cur["value"]) for _, _, cur, _ in rows]
    if any(v is None for v in vals):
        return []
    units, scale = row_units(rows[0][3], rec0.get("group", ""), cur0["value"], rec0.get("units", ""))
    ccy = _currency(rec0, cur0)
    if ccy and ccy != "USD" and units and units not in ("percent", "count", "as printed"):
        units = f"{ccy} {units}"
    repeated = {shown for _, _, _, shown in rows if sum(1 for r in rows if r[3] == shown) > 1}
    def named(rec, shown):
        # the group only where it tells two same-named rows apart (current / non-current term debt)
        return shown + (f" [{rec['group']}]" if shown in repeated and rec.get("group") else "")
    parts = " + ".join(f"{named(rec, shown)} {cur['value'].replace('$', '').strip()}" for _, rec, cur, shown in rows)
    when = period_from_heading(cur0.get("heading", "")).get("ended") or "the latest balance-sheet date"
    return [f"- DERIVED Total debt: {_scaled(f'{sum(vals):,.0f}', scale)} = {parts} (the debt rows above, lease liabilities excluded; "
            f"as of {when}; {units or 'as printed'})  {_source(src0, rec0)}"]


GROUPING_KPI_RE = re.compile(r"(?i)\bby\s+(?:reportable\s+|operating\s+|geographic(?:al)?\s+|product[/ ]?(?:service\s+)?)?"
                             r"(?:segments?|products?|categor(?:y|ies)|geograph\w*|regions?|brands?|business(?:es)?|lines?|types?|channels?|concepts?|divisions?)\b|"
                             r"\b(?:segment|revenue|sales) (?:mix|breakdown)\b")
_GENERIC_WORDS = {"revenue", "revenues", "sale", "sales", "net", "total", "margin", "margins", "percentage", "percent", "rate", "growth",
                  "income", "profit", "earning", "earnings", "share", "shares", "per", "eps", "value", "amount", "figure", "figures",
                  "metric", "metrics", "ratio", "ratios", "yoy", "year", "quarter", "change", "reported", "company", "the", "and", "of",
                  "for", "from", "in", "on", "to", "a", "an", "with", "its", "as", "by", "vs"}
_COST_RE = re.compile(r"(?i)\bcost|expense")


def _norm_words(text: str) -> set:
    t = re.sub(r"(?i)\beps\b", "earnings per share", text or "")
    return {w.rstrip("s") if len(w) > 3 else w for w in re.findall(r"[a-z0-9]+", t.lower())}


def _distinctive(name: str, entity_aliases: list = ()) -> set:
    words = _norm_words(name)
    for a in entity_aliases:
        words -= _norm_words(a)
    return {w for w in words if w not in {g.rstrip("s") if len(g) > 3 else g for g in _GENERIC_WORDS} and len(w) > 2}


def _kpi_entities(name: str, segments: list) -> list:
    low = (name or "").lower()
    out = []
    for seg in segments:
        for a in aliases(seg):
            al = a.lower()
            if (len(al) <= 6 and re.search(r"(?<![a-z0-9])" + re.escape(al) + r"(?![a-z0-9])", low)) or (len(al) > 6 and al in low):
                out.append(seg); break
    return out


_FLOW_CONTEXT_RE = re.compile(r"(?i)changes? in|\bincrease\b|\bdecrease\b|operating assets and liabilities|net cash|provided by|"
                              r"used in|generated by|statements? of cash flows?|cash flows? statements?")


def _cash_kpi_line(name: str, cash_lines: list):
    """The cash-flow summary line a cash-flow KPI names (capex / operating
    cash flow / free cash flow), re-labelled as that KPI; None otherwise."""
    low = (name or "").lower()
    want = ("Capital expenditures" if re.search(CASH_ROWS[1][1], low) or re.search(r"\bcapex\b", low) else
            "Operating cash flow" if re.search(CASH_ROWS[0][1], low) or re.search(r"operating cash flow|cash (?:generated|provided) by operat|cash from operations", low) else
            "Free cash flow" if re.search(r"free cash flow", low) else None)
    if not want:
        return None
    line = next((l for l in cash_lines or [] if l.startswith(f"- {want}:")), None)
    return line.replace(f"- {want}:", f"- KPI {name}:", 1) if line else None


def is_balance_kpi(name: str) -> bool:
    """A point-in-time balance (inventories, receivables, cash, debt…), not
    a flow, a change or a ratio."""
    return bool(re.search(r"(?i)inventor|receivable|payable|cash and (?:cash )?equivalents|\bdebt\b|borrowings|deferred revenue|backlog|"
                          r"total assets|total liabilities|stockholders['’]? equity|shareholders['’]? equity", name or "")) and \
        not re.search(r"(?i)change|growth|turnover|days|flow|increase|decrease|ratio|margin|%|percent", name or "")


def _derived_kpi(name: str, derived: list, segments: list = None):
    """A company-wide margin KPI satisfied by the computed margin line of the
    income table (run #29: 'Operating profit margin' was 'not found' beside a
    derived 60.3%). A KPI that names a segment never takes the company
    figure (run #26's entity rule)."""
    # a non-GAAP or segment KPI never takes the company's GAAP margin (2026-10-11)
    if not re.search(r"(?i)margin", name or "") or _kpi_entities(name, segments or []) or NON_GAAP_RE.search(name or "") \
            or re.search(r"(?i)\bsegments?\b", name or ""):
        return None
    words = set(re.findall(r"[a-z]+", (name or "").lower()))     # plain words: the stemmer turns "gross" into "gro"
    for ln in derived:
        m = re.match(r"^- DERIVED ((Gross|Operating|Net) margin): ([-\d.]+%) = (.+?)\s+(\[source:.*)$", ln)
        if m and m.group(2).lower() in words:
            return f"- KPI {name}: {m.group(3)} = {m.group(4)} (computed from the filed table)  {m.group(5)}"
    return None


def resolve_kpi(name: str, all_records: list, segments: list):
    """-> (src, rec, cur, prev, note) or None. The row must name the KPI's
    segment/product when the KPI names one (a company-total row never
    qualifies, unless the company has a single reportable segment — then the
    consolidated figure IS that segment and the line says so), and must carry
    at least half of the KPI's distinctive words otherwise. Rows under a
    cost or expense heading never satisfy a non-cost metric."""
    # word boundaries: "generated" is not a "rate" (run #29's operating cash flow KPI)
    wants_pct = bool(re.search(r"(?i)%|\bpercent|\bmargin|\bratio|\brates?\b|\bpenetration|\bmix\b", name))
    # "Non-GAAP operating income / operating margin" names an amount AND a
    # margin: either answers it (2026-10-11)
    if wants_pct and re.search(r"(?i)\b(?:income|revenue|sales|profit|earnings|ebitda?)\b\s*(?:/|and|&)", name):
        wants_pct = False
    wants_cost = bool(_COST_RE.search(name))
    wants_balance = is_balance_kpi(name)
    base = re.sub(r"(?i)\s*(?:%|percent(?:age)?)\s*of\s*(?:total\s+)?(?:revenues?|sales)\s*$", "", name)
    entities = _kpi_entities(name, segments)
    ent_aliases = [a for e in entities for a in aliases(e)]
    distinctive = _distinctive(base, ent_aliases)
    metric_words = _norm_words(base) - {w for a in ent_aliases for w in _norm_words(a)}
    best, best_score = None, 0.0
    for src, rec in all_records:
        label, group = rec["label"], rec.get("group", "")
        if BOILERPLATE_LABEL_RE.search(label):
            continue
        context = f"{label} {group}"
        if _COST_RE.search(context) and not wants_cost:
            continue
        # run #29: a balance ("Inventories") is never satisfied by its
        # cash-flow change ("Changes in operating assets and liabilities")
        if wants_balance and _FLOW_CONTEXT_RE.search(f"{context} {rec.get('caption', '')}"):
            continue
        if entities:
            if re.match(r"(?i)^(?:total|consolidated)\b", label):
                continue
            ent_cells = [c for c in rec["cells"] if c.get("entity") and _segment_of(c["entity"], entities)]
            row_names_entity = bool(_segment_of(label, entities))
            if not row_names_entity and not ent_cells:
                continue
            ctx_words = _norm_words(f"{label} {group} {rec.get('caption', '')}")
            overlap = len((metric_words - {"net", "total"}) & ctx_words) / max(1, len(metric_words - {"net", "total"}))
            phrase = 1.0 if re.sub(r"\s+", " ", " ".join(w for w in re.findall(r"[a-z]+", base.lower()) if w not in {a.lower() for a in ent_aliases})).strip() in context.lower() else 0.0
            score = overlap + phrase
            if score <= 0 and metric_words - {"net", "total"}:
                continue
            ent_key = _entity_key(ent_cells[0]) if (ent_cells and not row_names_entity) else None
            cur, prev = _pair_cells(rec["cells"], prefer_percent=wants_pct, entity=ent_key)
        else:
            score = max(label_matches(label, base), label_matches(f"{label} {group}", base))
            exact = any(label.strip().lower() == a.lower() for a in aliases(base))
            ctx_words = _norm_words(f"{label} {group}")
            if not exact:
                if score < 0.5:
                    continue
                if distinctive and len(distinctive & ctx_words) / len(distinctive) < 0.5:
                    continue
            cur, prev = _pair_cells(rec["cells"], prefer_percent=wants_pct)
            if wants_pct and cur is not None and "%" not in (cur.get("value") or "") and not PERCENT_COL_RE.search(cur.get("entity", "")):
                continue                         # run #29: a margin is never an amount row (the computed margin is used instead)
        if cur is None or num_of(cur.get("value")) is None or _stale(cur, src):
            continue
        if score > best_score:
            best, best_score = (src, rec, cur, prev, ""), score
    if best is None and entities and len(segments) == 1:
        # single reportable segment: the consolidated row is that segment
        metric = re.sub(r"(?i)\b" + "|".join(re.escape(a) for a in ent_aliases) + r"\b", "", base).strip() or "revenue"
        for src, rec in all_records:
            if re.match(r"(?i)^(?:total|consolidated)\b", rec["label"]) and label_matches(rec["label"], metric) >= 0.5 and not _COST_RE.search(rec["label"] + " " + rec.get("group", "")):
                cur, prev = _pair_cells(rec["cells"], prefer_percent=wants_pct)
                if cur is not None and num_of(cur.get("value")) is not None:
                    return src, rec, cur, prev, "single reportable segment: the consolidated figure is the segment's"
    return best


def _filed_fcf(all_records: list) -> list:
    """Free cash flow from the FILED statement (run #29): operating cash flow
    less capex from the same document and period — a statement printed across
    two tables still pairs (TSM). Inputs shown; the first pair per document."""
    out, by_src = [], {}
    for src, rec in all_records:
        by_src.setdefault(id(src), (src, []))[1].append(rec)
    for src, recs in by_src.values():
        ocf = next((r for r in recs if _is_ocf(r)), None)
        if not ocf:
            continue
        oc, _ = _pair_cells(ocf["cells"])
        ov = num_of(oc["value"]) if oc and not _stale(oc, src) else None
        # the same period and the same units: yen billions are never taken from
        # yen millions (2026-10-11, a supplemental table beside the statement)
        ounits = row_units(ocf["label"], ocf.get("group", ""), (oc or {}).get("value", ""), ocf.get("units", ""))[0]
        def fits(r):
            c = _pair_cells(r["cells"])[0]
            u = row_units(r["label"], r.get("group", ""), c.get("value", ""), r.get("units", ""))[0] if c else ""
            # units unknown on one side (a "(Continued)" page that does not repeat them) is no conflict
            return bool(c) and c["period"] == (oc or {}).get("period") and (u == ounits or "as printed" in (u, ounits))
        capex = next((r for r in recs if _is_capex(r) and fits(r) and (num_of(_pair_cells(r["cells"])[0]["value"]) or 0) < 0), None) or \
            next((r for r in recs if _is_capex(r) and fits(r)), None)
        if ov is None or not capex:
            continue
        cc, _ = _pair_cells(capex["cells"])
        cv = num_of(cc["value"]) if cc else None
        if cv is None:
            continue
        units = " ".join(x for x in (ocf.get("currency") or "", ocf.get("units") or "") if x) or "as printed"
        out.append(f"- DERIVED Free cash flow: {ov - abs(cv):,.0f} = {ocf['label']} {oc['value']} − capital expenditures "
                   f"({capex['label']}) {abs(cv):,.0f} ({oc['period']}; {units})  {_source(src, ocf)}")
    return out


def derived_lines(all_records: list, segments: list) -> list:
    """Margins from revenue + profit rows in the same table and period, the
    residual margin after listed cost ratios, segment-sum and stated-growth
    sanity checks, and free cash flow from the filed statement. Every line
    shows its formula and inputs."""
    fcf = list(_filed_fcf(all_records))
    out, margins = [], {}          # margins: (metric, period) -> (revenue, order, line)
    by_table = {}
    for src, rec in all_records:
        by_table.setdefault((id(src), rec["table"]), []).append((src, rec))
    for (_, _t), rows in by_table.items():
        src = rows[0][0]
        recs = [r for _, r in rows]
        def find(pat):
            for r in recs:
                if re.search(pat, r["label"].strip().lower()):
                    return r
            return None
        rev = find(INCOME_ROWS[0][1])
        nii, nonii = find(r"^net interest income(?:\s*\(.*\))?$"), find(r"^(?:total )?non-?interest income$")
        if not rev and nii and nonii:
            a, ap = _pair_cells(nii["cells"])
            b, bp = _pair_cells(nonii["cells"])
            if a and b and a["period"] == b["period"] and num_of(a["value"]) is not None and num_of(b["value"]) is not None \
                    and not _stale(a, src):
                now = num_of(a["value"]) + num_of(b["value"])
                ago = (num_of(ap["value"]) + num_of(bp["value"])) if ap and bp and num_of(ap["value"]) is not None \
                    and num_of(bp["value"]) is not None else None
                vs = f" vs {ago:,.0f} year-ago; change {(now / ago - 1) * 100:+.1f}%" if ago else ""
                out.append(f"- DERIVED Revenue: {now:,.0f} = {nii['label']} {a['value']} + {nonii['label']} {b['value']} "
                           f"({a['period']}; a bank's revenue){vs}  {_source(src, nii)}")
        if rev:
            rc, _ = _pair_cells(rev["cells"])
            # a percentage is never an amount to divide ("Gross margin 75.0%" by
            # revenue read 0.1%, 2026-10-11)
            rv = num_of(rc["value"]) if rc and "%" not in (rc.get("value") or "") and rc.get("period") != "change" and not _stale(rc, src) else None
            if rv:
                for name, pat in (("Gross margin", INCOME_ROWS[1][1]), ("Operating margin", INCOME_ROWS[2][1]), ("Net margin", INCOME_ROWS[3][1])):
                    r = find(pat)
                    if not r:
                        continue
                    c, _ = _pair_cells(r["cells"])
                    v = num_of(c["value"]) if c and c["period"] == rc["period"] and "%" not in (c.get("value") or "") else None
                    if v is not None:
                        # per metric and period, the company's: the largest revenue
                        # (a segment's own table is smaller), the first table on a tie
                        key = (name, rc["period"])
                        if key not in margins or abs(rv) > abs(margins[key][0]):
                            margins[key] = (rv, len(margins), f"- DERIVED {name}: {v / rv * 100:.1f}% = {r['label']} {c['value']} / {rev['label']} "
                                                              f"{rc['value']} ({rc['period']})  {_source(src, rev)}")
        # residual margin after cost ratios printed as % of revenue
        pct_rows = []
        for r in recs:
            if not re.search(r"(?i)cost|expense|labor|labour|occupancy|food|beverage", r["label"]) or re.search(r"(?i)total|income|tax|interest|depreciation|amortization|impairment|preopening|general and administrative|g&a", r["label"]):
                continue
            pc = [c for c in r["cells"] if PERCENT_COL_RE.search(c.get("entity", "")) and "%" in (c.get("value") or "")]
            if pc and all(r["label"] != lab for lab, _ in pct_rows):         # a cost line printed twice counts once
                pct_rows.append((r["label"], pc[0]))
        if len(pct_rows) >= 2:
            vals = [(lab, num_of(c["value"])) for lab, c in pct_rows]
            vals = [(lab, v) for lab, v in vals if v is not None]
            if vals:
                total = sum(v for _, v in vals)
                out.append(f"- DERIVED residual margin after the listed cost ratios: {100 - total:.1f}% = 100% − "
                           + " − ".join(f"{lab} {v:g}%" for lab, v in vals) + f" ({pct_rows[0][1]['period']}; the cost lines a filer prints as % of revenue; "
                           f"not a reported margin)  {_source(src, recs[0])}")
        # segment sum: entity columns of a revenue row vs its Total column
        for r in recs:
            if not re.search(INCOME_ROWS[0][1], r["label"].strip().lower()):
                continue
            ents = [c for c in r["cells"] if c.get("entity") and _segment_of(c["entity"], segments)]
            tot = next((c for c in r["cells"] if re.search(r"(?i)^total|consolidated", c.get("entity", ""))), None)
            if len(ents) >= 2 and tot:
                parts = [(c["entity"], num_of(c["value"])) for c in ents]
                tv = num_of(tot["value"])
                if tv and all(v is not None for _, v in parts):
                    s = sum(v for _, v in parts)
                    gap = (s / tv - 1) * 100
                    other = [c for c in r["cells"] if c.get("entity") and c not in ents and c is not tot]
                    verdict = "OK" if abs(gap) <= 1.0 or other else f"MISMATCH ({gap:+.1f}%)"
                    out.append(f"- SANITY CHECK segment sum {verdict}: " + " + ".join(f"{e} {v:,.0f}" for e, v in parts)
                               + (f" + other columns {', '.join(c['entity'] for c in other)}" if other else "")
                               + f" vs {tot['entity']} {tv:,.0f} ({r['label']}, {tot['period']})  {_source(src, r)}")
        # stated growth vs computed from the two values of a matching value row
        for r in recs:
            if not re.search(r"(?i)growth|change|vs\.? prior|year[- ]over[- ]year|yoy", r["label"]):
                continue
            gcell, _ = _pair_cells(r["cells"])
            if not gcell or "%" not in (gcell.get("value") or ""):
                continue
            base_label = re.sub(r"(?i)\b(?:yoy|growth|rate|change|vs\.? prior year|year[- ]over[- ]year)\b", "", r["label"]).strip(" :-")
            base = next((b for b in recs if b is not r and label_matches(b["label"], base_label) >= 0.6 and "%" not in (b["cells"][0]["value"] if b["cells"] else "%")), None)
            if base:
                bc, bp = _pair_cells(base["cells"])
                a, b = (num_of(bc["value"]) if bc else None), (num_of(bp["value"]) if bp else None)
                g = num_of(gcell["value"])
                if a is not None and b and g is not None:
                    implied = (a / b - 1) * 100
                    verdict = "OK" if abs(implied - g) <= 0.6 else f"MISMATCH (stated {g:g}%, implied {implied:.1f}%)"
                    out.append(f"- SANITY CHECK stated growth {verdict}: {r['label']} {gcell['value']} vs {base['label']} {bc['value']} / {bp['value']} − 1 = {implied:.1f}%  {_source(src, r)}")
    # the latest quarter's margins first, then longer periods; the cap applies
    # after ordering (2026-10-11: an annual table first left no room for the quarter's)
    rank = {"quarter": 0, "YTD (H1)": 1, "YTD (9M)": 2, "annual": 3, "ttm": 4}
    names = {"Gross margin": 0, "Operating margin": 1, "Net margin": 2}
    ordered = [m[2] for k, m in sorted(margins.items(), key=lambda kv: (rank.get(kv[0][1], 5), names[kv[0][0]], kv[1][1]))]
    return (fcf + ordered + out)[:max(MAX_LINES["derived"], len(fcf) + len(ordered))]
