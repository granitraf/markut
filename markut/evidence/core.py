def balance_row(label: str, prior: str):
    """(name, is_debt) for a balance-sheet row, or None. A bare "Total" right
    after the non-current assets total is total assets (TSM prints "TOTAL")."""
    low = _NOTE_REF_RE.sub("", label or "").strip().lower()
    if low == "total" and re.match(r"(?i)^total non-?current assets", _NOTE_REF_RE.sub("", prior or "").strip()):
        return "Total assets", False
    for name, pat, debt in BALANCE_ROWS:
        if re.search(pat, low):
            return name, debt
    return None


