def test_the_quality_block_reports_completeness_and_consistency():
    b, s = quality.quality_block(RUN29, unanchored=["42% (Q4)"])
    check(f"TSM run #29: statements found are listed ({b})", "income ✓" in b and "cash flow ✓" in b and "balance ✓" in b)
    check("…the filing's +36.0% and the provider's 36.00% agree", "revenue growth" in b.lower() and "agree" in b)
    check("…the provider's debt/equity matches a computed line", "debt/equity" in b.lower())
    check("…the planner's 42% is named as not evidence", "42% (Q4)" in b and "not evidence" in b)
    check("…the trimmed profile KPIs are reported", "5 of 8 KPIs shown" in b)
    check("…nothing is suspect", s["suspect"] == 0 and s["disputed"] == 0)
    b28, s28 = quality.quality_block(RUN28, unanchored=[])
    check(f"TSM run #28: the 47.84% FCF yield and the 0.5x P/E band are suspect ({b28})",
          s28["suspect"] >= 2 and "47.84%" in b28 and "0.5x" in b28)
    check("TSM run #28: no filings -> income and cash flow not found", "income ✗" in b28 and "cash flow ✗" in b28)


def test_a_filing_and_provider_disagreement_is_disputed():
    aapl = RUN29.replace("change +36.0%", "change +16.4%").replace("36.00%", "12.00%")
    b, s = quality.quality_block(aapl, unanchored=[])
    check(f"AAPL-shaped: filing +16.4% vs provider 12.00% for the same quarter is disputed ({b})", s["disputed"] == 1 and "disagree" in b)


def test_the_gate_and_the_judge_use_it():
    packet = RUN28.replace("[filings unavailable: no 20-F in the filing history searched]", "Sources: 6-K") \
                  .replace("[KEY QUESTIONS]", "[KEY QUESTIONS]\n\n" + quality.quality_block(RUN28, [])[0] + "\n")
    g = gate.lean_gate({"evidence": packet, "coverage": {"Q1": 2, "Q2": 1, "Q3": 1, "Q4": 1, "Q5": 1}})
    check(f"suspect figures in the packet cap the lean at low ({g})", g["allowed"] and g["cap"] == "low" and "suspect" in g["reason"])
    clean = RUN29.replace("[KEY QUESTIONS] (set by the planner)", "[KEY QUESTIONS]\n\n" + quality.quality_block(RUN29, [])[0] + "\n")
    g2 = gate.lean_gate({"evidence": clean, "coverage": {"Q1": 2, "Q2": 1, "Q3": 1, "Q4": 1, "Q5": 1}})
    check("a clean packet is not capped", g2["allowed"] and not g2["cap"])
    check("the judge is told how to read it", "EVIDENCE QUALITY" in prompts.JUDGE_SYSTEM_PROMPT)
    from markut.guardrails import tracer
    check("the quality block is never traced as evidence", "47.84%" not in tracer.tracing_evidence("[EVIDENCE QUALITY]\n- Suspect: FCF yield 47.84%"))


