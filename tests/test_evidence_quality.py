"""Evidence quality, computed in code before the debate (2026-10-11, after
run #29 TSM). The report is only as good as the packet, so the packet now
says how good it is: which statements were found, how many questions have
current evidence, whether a filing figure and the provider's agree for the
same metric and period, which figures are out of range, which figures exist
only in model-written text, and what was trimmed to fit. Figures the
profiler read in the filings are carried into the data with their sentence.
Offline; TSM-run-#29-shaped, TSM-run-#28-shaped and AAPL-shaped packets."""
from markut.agents import gate, prompts
from markut.evidence import quality


def check(label, condition):
    assert condition, label


