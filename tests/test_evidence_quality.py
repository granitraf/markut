def test_profile_figures_are_carried_into_the_data():
    block, unanchored = quality.profile_evidence(RUN29, SECTIONS)
    check(f"TSM run #29: the profile's 77% is carried with its release sentence and source ({block})",
          "accounted for 77% of total wafer revenue" in block and "6-K a2q26e_withguidancexfinal.htm" in block and "filed 2026-07-16" in block)
    check(f"…the planner's 42%, found in no section read, stays listed as not anchored ({unanchored})", any(u.startswith("42%") for u in unanchored))
    from markut.guardrails import tracer
    check("the carried sentence is data the governor can trace", tracer.trace_claim("77%", tracer.tracing_evidence(RUN29 + "\n" + block)) == "CITED")
    aapl_sections = [{"name": "8-K a8-kex991.htm (results release)", "filing_date": "2026-07-30",
                      "text": "Diluted earnings per share of $2.02 included a favorable impact of $0.11 from tariff refunds."}]
    aapl_packet = "[KEY QUESTIONS]\n- Q4: How much of EPS is the $0.11 tariff refund?\n[FILINGS]\n- Revenue: 109,417 million  [source: T1]"
    b2, u2 = quality.profile_evidence(aapl_packet, aapl_sections)
    check(f"AAPL run #27: the planner's $0.11 is carried with the release sentence ({b2})", "$0.11 from tariff refunds" in b2 and u2 == [])


def test_the_summary_reaches_the_page_and_the_pdf():
    from markut.web import events as ev
    packet = RUN29.replace("[KEY QUESTIONS] (set by the planner)", "[KEY QUESTIONS]\n\n" + quality.quality_block(RUN29, ["42% (Q4)"])[0] + "\n")
    e = ev.event_for("review", {"verdict": "v", "review_report": {}}, {"verdict": "v", "evidence": packet, "judge_decision": {}}, {})
    q = e["data"].get("quality") or ""
    check(f"the review event carries a one-line evidence summary ({q!r})", "questions covered" in q and "not in the data" in q)
    import re
    import pypdfium2 as pdfium
    from markut.report import build_report
    run = {"id": 1, "ticker": "TSM", "started_at": "2026-10-11", "events": [
        {"event": "start", "data": {"ticker": "TSM", "max_rounds": 2}},
        {"event": "review", "data": {"verdict": "v. Research, not investment advice.", "stats": {}, "quality": q,
                                     "lean": {"lean": "neutral", "confidence": "low", "reason": "offset"}}}]}
    doc = pdfium.PdfDocument(build_report(run))
    t = re.sub(r"\s+", " ", " ".join(doc[i].get_textpage().get_text_range() for i in range(len(doc))))
    check("the PDF shows it", "Evidence:" in t and "questions covered" in t)


PLAN = {"key_questions": [{"id": f"Q{i}", "question": q} for i, q in enumerate([
    "Can the advanced-technology share (77% in 2Q26) keep rising?", "Will gross margin hold?", "Is capex covered by cash flow?",
    "How concentrated is growth in North America (net revenue up 42% in 2025)?", "Are inventories growing faster than sales?"], 1)],
    "what_would_mislead": ["TTM free cash flow yield reflects peak capex."]}
PROFILE = {"business": "A foundry; advanced technologies were 77% of wafer revenue in 2Q26.", "archetype": "hardware"}
FILINGS = "\n".join(RUN29.splitlines()[4:16])
MARKET = "\n".join(RUN29.splitlines()[16:25])


def test_the_packet_carries_both_blocks_after_the_key_questions():
    from markut.evidence.assembly import assemble_packet
    cov = {"Q1": 2, "Q2": 1, "Q3": 0, "Q4": 1, "Q5": 1}
    packet, _ = assemble_packet(PROFILE, PLAN, FILINGS, MARKET, "", cov, profile_sections=SECTIONS)
    i = {h: packet.find(h) for h in ("[KEY QUESTIONS]", "[EVIDENCE QUALITY]", "[PROFILE EVIDENCE]", "[FILINGS]")}
    check(f"TSM run #29 shape: key questions -> evidence quality -> profile evidence -> filings ({i})",
          -1 < i["[KEY QUESTIONS]"] < i["[EVIDENCE QUALITY]"] < i["[PROFILE EVIDENCE]"] < i["[FILINGS]"])
    check("…coverage comes from the coverage gate, not a guess", "4 of 5 questions covered" in packet and "open: Q3" in packet)
    check("…the 77% is carried with its release sentence", "accounted for 77% of total wafer revenue" in packet)
    check("…the planner's 42% is named as not evidence", "42% (Q4)" in packet)
    bare, _ = assemble_packet({}, PLAN, "[FILINGS]\n[filings unavailable: no annual report in the filing history searched]",
                              "[VALUATION]\n- FCF yield (TTM FCF / market cap): 47.84%  [source: computed]", "", {f"Q{i}": 0 for i in range(1, 6)})
    check("no-filings shape: nothing found, both planner figures listed, the yield suspect",
          "income ✗" in bare and "0 of 5 questions covered" in bare and "77% (Q1)" in bare and "42% (Q4)" in bare
          and "SUSPECT: FCF yield 47.84%" in bare and "[PROFILE EVIDENCE]" not in bare)


def test_the_profiler_hands_on_the_sections_it_read(monkeypatch):
    from markut import store
    from markut.agents import profiler
    from markut.evidence import sections as secs
    text = "\n\n".join(s["text"] for s in SECTIONS)
    spans = [{"name": s["name"], "filing_date": s["filing_date"], "chars": len(s["text"])} for s in SECTIONS]
    monkeypatch.setattr(secs, "filing_set", lambda t: {"fingerprint": "F"})
    monkeypatch.setattr(store, "cache_put", lambda key, value, db=None: True)
    cached = {"profile": dict(PROFILE, table_index=[]), "gaps": [], "profiled_text": text, "sources": ["s"], "spans": spans}
    monkeypatch.setattr(store, "cache_get", lambda key, db=None: dict(cached))
    out = profiler.profiler_node({"ticker": "TSM"})
    got = [(s["name"], s["filing_date"], s["text"]) for s in out.get("profiled_sections") or []]
    check(f"a cached profile returns each section it read, named and dated ({[g[:2] for g in got]})",
          got == [(s["name"], s["filing_date"], s["text"]) for s in SECTIONS])
    legacy = {k: v for k, v in cached.items() if k != "spans"}
    monkeypatch.setattr(store, "cache_get", lambda key, db=None: dict(legacy))
    old = profiler.profiler_node({"ticker": "TSM"})["profiled_sections"]
    check(f"a profile cached before this change still hands on its text, with an honest source ({[s['name'] for s in old]})",
          len(old) == 1 and old[0]["text"] == text and "not recorded" in old[0]["name"])
    from markut.agents.state import DebateState
    check("the state carries the sections", "profiled_sections" in DebateState.__annotations__)


