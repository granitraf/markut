"""Readiness check (2026-10-11): for ANY ticker, is the evidence an accurate
report needs present and sound? Scored by general rules from the packet the
pipeline builds — statements found and dated, a real year-ago comparison,
units and currency on every amount, filings current, no suspect or disputed
figure. Offline: synthetic packets of each shape."""
from markut import readiness


def check(label, condition):
    assert condition, label


INFO = {"filings": True, "filer_type": "domestic",
        "annual": {"form": "10-K", "filing_date": "2025-10-31"},
        "interim": {"form": "10-Q", "filing_date": "2026-07-31"},
        "earnings": {"form": "8-K", "filing_date": "2026-07-30"}}
CORE = "\n".join([
    "[CORE FIGURES] (extracted by code)",
    "-- Income statement summary --",
    "- Revenue: Total net sales: 109,417 million (quarter, Three Months Ended June 27, 2026) vs 94,036 million year-ago (June 28, 2025); change +16.4%  (millions; GAAP; company-wide)  [source: T1]",
    "- Net income: 29,000 million (quarter, Three Months Ended June 27, 2026) vs 23,434 million year-ago (June 28, 2025); change +23.8%  (millions; GAAP; company-wide)  [source: T1]",
    "-- Cash flow summary --",
    "- Operating cash flow: Cash generated by operating activities: 116,996 million (YTD (9M), Nine Months Ended June 27, 2026) vs 81,754 million year-ago (June 28, 2025)  (millions; GAAP; company-wide)  [source: T2]",
    "-- Balance sheet summary --",
    "- Cash and cash equivalents [Current assets]: $39,544 million as of June 27, 2026 vs $35,934 million as of September 27, 2025  (millions; GAAP; point-in-time balance)  [source: T3]",
    "- Total assets: $383,266 million as of June 27, 2026 vs $359,241 million as of September 27, 2025  (millions; GAAP; point-in-time balance)  [source: T3]",
    "-- Lease liabilities (balance sheet or lease note) --",
    "- no lease-liability row",
    "-- Derived metrics and sanity checks (computed in code) --",
    "- DERIVED Gross margin: 50.1% = Gross margin 54,819 / Total net sales 109,417 (quarter)  [source: T1]",
])
MARKET = "\n".join(["[QUOTE & VALUATION]", "- Price (current): $255.00  [source: yfinance/info]", "- Market cap: $3.80T  [source: yfinance/info]",
                    "[FUNDAMENTALS]", "- Revenue growth (MRQ YoY, quarter ended 2026-06-30 vs the year-ago quarter): 16.40%  [source: yfinance/info]"])


def _kinds(r):
    return {i["type"] for i in r["issues"]}


def test_a_complete_packet_is_ready():
    r = readiness.score("AAA", INFO, CORE, MARKET, today="2026-10-11")
    check(f"a US-filer-shaped packet with every statement dated and labelled is READY ({r})", r["verdict"] == "READY" and not r["issues"])


def test_each_failure_is_named_by_type():
    r = readiness.score("NOF", {"filings": False, "reason": "no annual report in the filing history searched"}, "", MARKET, today="2026-10-11")
    check(f"no SEC filings -> NOT READY, said why ({r})", r["verdict"] == "NOT READY" and "no_filings" in _kinds(r))
    stale = dict(INFO, earnings={"form": "8-K", "filing_date": "2026-05-01"}, interim={"form": "10-Q", "filing_date": "2026-08-03"})
    r = readiness.score("STL", stale, CORE, MARKET, today="2026-10-11")
    check(f"an earnings release a quarter older than the interim report is stale ({r['issues']})", "stale_release" in _kinds(r) and r["verdict"] == "PARTIAL")
    old = dict(INFO, annual={"form": "10-K", "filing_date": "2024-03-01"}, interim=None, earnings=None)
    check("filings more than 200 days old", "old_filings" in _kinds(readiness.score("OLD", old, CORE, MARKET, today="2026-10-11")))
    no_inc = CORE.replace("- Revenue: Total net sales", "- Other: Total other")
    r = readiness.score("NOI", INFO, no_inc, MARKET, today="2026-10-11")
    check(f"no revenue line -> NOT READY ({r['issues']})", r["verdict"] == "NOT READY" and "no_revenue" in _kinds(r))
    r = readiness.score("UND", INFO, CORE.replace("(quarter, Three Months Ended June 27, 2026) vs 94,036 million year-ago (June 28, 2025)", "(unstated)"),
                        MARKET, today="2026-10-11")
    check(f"an undated revenue figure ({r['issues']})", "undated" in _kinds(r))
    r = readiness.score("QOQ", INFO, CORE.replace("vs 94,036 million year-ago (June 28, 2025)", "vs 104,000 million prior period (March 28, 2026)"),
                        MARKET, today="2026-10-11")
    check("no year-ago comparison for revenue", "no_year_ago" in _kinds(r))
    r = readiness.score("NCF", INFO, CORE.replace("- Operating cash flow:", "- Something else:"), MARKET, today="2026-10-11")
    check("no operating cash flow", "no_cash_flow" in _kinds(r))
    r = readiness.score("NBS", INFO, CORE.replace("- Cash and cash equivalents", "- none found by table structure").replace("- Total assets: $383,266", "- none: x"),
                        MARKET, today="2026-10-11")
    check("no balance sheet", "no_balance_sheet" in _kinds(r))
    r = readiness.score("UNT", INFO, CORE.replace("(millions; GAAP; company-wide)  [source: T1]", "(as printed; GAAP; company-wide)  [source: T1]"),
                        MARKET, today="2026-10-11")
    check(f"amounts with no units ({r['issues']})", "units_missing" in _kinds(r))
    fx = MARKET + "\n- CURRENCY NOTE: the price, market cap and per-share market data are in USD (the traded security); the financial statements are in TWD and are labelled TWD, never '$'."
    r = readiness.score("CCY", dict(INFO, filer_type="foreign_private"), CORE, fx, today="2026-10-11")
    check(f"a foreign filer's amounts without their currency ({r['issues']})", "currency_unlabelled" in _kinds(r))
    r = readiness.score("OKC", dict(INFO, filer_type="foreign_private"), CORE.replace("(millions; GAAP", "(TWD millions; GAAP"), fx, today="2026-10-11")
    check("…labelled, they are fine", "currency_unlabelled" not in _kinds(r))
    r = readiness.score("MKT", INFO, CORE, "[QUOTE & VALUATION]\n[market data unavailable: HTTP 429]", today="2026-10-11")
    check("no market data", "no_market_data" in _kinds(r))
    sus = MARKET + "\n[VALUATION]\n- FCF yield (TTM FCF / market cap): 47.84%  [source: computed]"
    r = readiness.score("SUS", INFO, CORE, sus, today="2026-10-11")
    check(f"a suspect figure from the evidence-quality check ({r['issues']})", "suspect_figure" in _kinds(r))
    dis = MARKET.replace("16.40%", "9.00%")
    check("a filing and provider disagreement", "disputed_figure" in _kinds(readiness.score("DIS", INFO, CORE, dis, today="2026-10-11")))


def test_the_summary_counts_failures_by_type():
    rows = [readiness.score("AAA", INFO, CORE, MARKET, today="2026-10-11"),
            readiness.score("NOF", {"filings": False, "reason": "x"}, "", MARKET, today="2026-10-11"),
            readiness.score("NCF", INFO, CORE.replace("- Operating cash flow:", "- Something else:"), MARKET, today="2026-10-11")]
    s = readiness.summarize(rows)
    check(f"verdict counts and issue counts by type ({s})", "READY 1" in s and "NOT READY 1" in s and "PARTIAL 1" in s
          and "no_filings" in s and "no_cash_flow" in s)


def test_revenue_and_net_income_under_any_label():
    for label in ("Total revenues", "Net Operating Revenues", "TOTAL OPERATING REVENUES", "Net sales", "Revenues"):
        core = CORE.replace("- Revenue: Total net sales:", f"- {label}:")
        r = readiness.score("LBL", INFO, core, MARKET, today="2026-10-11")
        check(f"'{label}' is the revenue line ({r['issues']})", "no_revenue" not in {i['type'] for i in r["issues"]})
    core = CORE.replace("- Net income:", "- Net Income Attributable to Shareowners of The Company:")
    check("a net income line under the company's own label", "no_net_income" not in
          {i["type"] for i in readiness.score("NI", INFO, core, MARKET, today="2026-10-11")["issues"]})


def test_rescoring_from_saved_text_needs_no_network():
    row = dict(readiness.score("AAA", INFO, CORE, MARKET, today="2026-10-11"), text={"info": INFO, "core": CORE, "market": MARKET})
    again = readiness.rescore([row], today="2026-10-11")
    check("a saved row is scored again from its own text", again[0]["verdict"] == "READY" and again[0]["ticker"] == "AAA")
