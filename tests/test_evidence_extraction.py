def test_the_search_only_looks_for_what_is_still_missing():
    q4 = {"id": "Q4", "question": "How much of the margin is the tariff refund?",
          "kpis": ["Products gross margin percentage", "Diluted EPS", "Tariff refund impact"]}
    known = {"Products gross margin percentage": True, "Diluted earnings per share": True}
    check(f"AAPL run #27 Q4: only the tariff impact is still missing ({questions.missing_kpis(q4, known)})",
          questions.missing_kpis(q4, known) == ["Tariff refund impact"])
    q3 = {"id": "Q3", "question": "Is capex supported by cash generation?",
          "kpis": ["Capital expenditures", "Annual wafer capacity", "Net cash generated by operating activities"]}
    check("TSM run #29 Q3: operating cash flow is known, capex and capacity are not",
          questions.missing_kpis(q3, {"Net cash generated by operating activities": True}) == ["Capital expenditures", "Annual wafer capacity"])
    check("nothing missing -> nothing to search", questions.missing_kpis(q4, {k: True for k in q4["kpis"]}) == [])


