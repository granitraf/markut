"""Packet completeness and accuracy (2026-10-11, after run #29 TSM).

The report is only as good as the packet: the judge rules against it and the
governor checks figures exist in it, but neither can see a figure the packet
missed or mislabeled. Run #29 measured three such holes, fixed here:
(1) no cash-flow line from the filings for AAPL or TSM — the patterns knew
only "net cash provided by" / "purchases of property"; (2) KPI matches of the
wrong type — "Gross profit margin" shown as the gross profit amount,
"Inventories" shown as the cash-flow change; (3) gaps declared without
looking — half-year and nine-month figures never counted as current, and an
uncovered question was never searched for in the filings' full text.
Offline; AAPL-shaped, TSM-shaped and synthetic (US "provided by") cases."""
from markut.evidence import core, questions


def check(label, condition):
    assert condition, label


def _core(monkeypatch, html, kpis=None, form="10-Q"):
    monkeypatch.setattr(core, "core_sources", lambda fs: [{"form": form, "name": "doc.htm", "filing_date": "2026-07-31", "url": "u",
                                                           "html": html, "text": "", "headline_period": "quarter"}])
    return core.extract_core({}, {"segments": [], "company_kpis": [{"name": k} for k in (kpis or [])]}, None)["text"]


