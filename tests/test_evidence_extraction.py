def _kpi_line(t, name):
    return next((l for l in t.splitlines() if l.startswith(f"- KPI {name}:") or l.startswith(f"- KPI value not found: {name}")), "")


def test_kpi_matches_have_the_right_type(monkeypatch):
    t = _core(monkeypatch, TSM_RELEASE, ["Gross profit margin", "Operating profit margin", "Inventories"], form="6-K")
    gm, om, inv = _kpi_line(t, "Gross profit margin"), _kpi_line(t, "Operating profit margin"), _kpi_line(t, "Inventories")
    check(f"TSM run #29: a margin KPI shows a margin (67.7%), never the gross profit amount ({gm[:160]!r})",
          "67.7%" in gm and "860,311 million" not in gm.split("(DERIVED")[0])
    check(f"TSM run #29: the operating margin KPI uses the computed 60.3% instead of 'not found' ({om[:160]!r})", "60.3%" in om)
    check(f"TSM run #29: an inventory KPI shows the balance, never the cash-flow change ({inv[:160]!r})",
          "385,500" in inv and "97,415,057" not in inv)
    pct = ("<html><body><p>Gross margin percentage (In percent)</p><table><tr><td></td><td>Three Months Ended June 27, 2026</td>"
           "<td>Three Months Ended June 28, 2025</td></tr><tr><td>Gross margin percentage</td><td>50.1 %</td><td>46.5 %</td></tr></table></body></html>")
    a = _kpi_line(_core(monkeypatch, pct, ["Gross margin percentage"]), "Gross margin percentage")
    check(f"AAPL-shaped: a printed percentage row still satisfies a margin KPI ({a[:120]!r})", "50.1" in a)
    syn = ("<html><body><p>Restaurant operating results (in thousands)</p><table><tr><td></td><td>Twenty-Six Weeks Ended July 4, 2026</td>"
           "<td>Twenty-Six Weeks Ended June 28, 2025</td></tr><tr><td>Restaurant-level operating margin</td><td>17.2%</td><td>16.1%</td></tr>"
           "<tr><td>Restaurant-level operating profit</td><td>412,000</td><td>371,000</td></tr></table></body></html>")
    s = _kpi_line(_core(monkeypatch, syn, ["Restaurant-level operating margin"]), "Restaurant-level operating margin")
    check(f"synthetic restaurant: the margin KPI takes the % row, not the profit amount ({s[:120]!r})", "17.2%" in s and "412,000" not in s)


# ---------------------------------------------------------------- (3) look before declaring a gap
def test_half_year_and_nine_month_values_are_current():
    text = ("- KPI Net cash generated by operating activities: 1,482,341,242 (YTD (H1), Six Months Ended June 30, 2026) vs …  [source: T3]\n"
            "- KPI Capital expenditures: (6,799) (YTD (9M), Nine Months Ended June 27, 2026) vs (9,473)  [source: T2]")
    plan = {"key_questions": [{"id": "Q3", "question": "Is capex supported by cash generation?", "kpis": ["Net cash generated by operating activities"]},
                              {"id": "Q4", "question": "How large is capex?", "kpis": ["Capital expenditures"]}]}
    cov = questions.coverage_assess(text, plan, {"Net cash generated by operating activities": True, "Capital expenditures": True})
    check(f"TSM run #29: an H1 value is current-period ({cov['Q3']})", cov["Q3"]["covered"] and not cov["Q3"]["missing"])
    check("AAPL-shaped: a nine-month value too", cov["Q4"]["covered"])


DOCS = [{"form": "6-K", "name": "rel.htm", "filing_date": "2026-07-16", "url": "https://sec.example/rel.htm",
         "text": ("TSMC today announced results for the second quarter. Capital expenditures for the first half of 2026 totaled "
                  "US$21.6 billion, and the Company expects 2026 capital expenditures of US$52 billion to US$56 billion. "
                  "The board approved a cash dividend of NT$7.0 per share.")},
        {"form": "10-Q", "name": "q.htm", "filing_date": "2026-07-31", "url": "https://sec.example/q.htm",
         "text": "Comparable restaurant sales increased 3.4% in the second quarter, driven by higher check averages. Traffic declined 1.0%."}]


def test_full_text_search_before_a_gap():
    q3 = {"id": "Q3", "question": "Is the 2026 capital expenditure plan supported by cash generation?", "kpis": ["Capital expenditures"]}
    lines = questions.full_text_sweep(q3, DOCS, [])
    check(f"TSM-shaped: the capex sentence is found in the current 6-K ({lines})",
          lines and "US$21.6 billion" in lines[0] and "current period (6-K filed 2026-07-16)" in lines[0] and "found by full-text search" in lines[0])
    check("…the dividend sentence is not a capex figure", not any("cash dividend" in l for l in lines))
    syn = questions.full_text_sweep({"id": "Q1", "question": "Can comparable restaurant sales keep growing?", "kpis": ["Comparable restaurant sales"]},
                                    DOCS, [])
    check(f"synthetic restaurant: a comparable-sales figure in the 10-Q text ({syn})", syn and "3.4%" in syn[0])
    none = questions.full_text_sweep({"id": "Q1", "question": "How large is the installed base of active devices?",
                                      "kpis": ["Installed base of active devices"]}, DOCS, [])
    check("AAPL-shaped: a metric no filing states is not invented", none == [])


def test_a_remaining_gap_says_the_full_text_was_searched():
    from markut.evidence.assembly import coverage_block
    block = coverage_block({"Q1": 0}, {"key_questions": [{"id": "Q1", "question": "How large is the installed base?"}]}, 1,
                           detail={"Q1": {"missing": ["Installed base of active devices"], "relevant": 0, "searched": True}})
    check(f"the gap line says the filings' full text was searched ({block})", "searched the full text of the current filings" in block)


def test_stray_amounts_in_headings_do_not_split_columns():
    # TSM's real interim cash-flow statement: the continuation table's
    # headings carry stray amounts ("Six Months Ended June 30 $ (744,405)"),
    # which made each column look like a different entity — the 2025 capex
    # was shown as current with no comparison
    cells = [{"heading": "Six Months Ended June 30 $ (744,405)", "period": "YTD (H1)", "entity": "$ (744,405)", "value": "(846,764,746)"},
             {"heading": "Six Months Ended June 30 $ (128,359)", "period": "YTD (H1)", "entity": "$ (128,359)", "value": "(628,052,531)"}]
    from markut.evidence.edgar import _strip_period_words
    check("an amount is never a column's name", _strip_period_words("Six Months Ended June 30 $ (744,405)") == "")
    cur, prev = core._pair_cells([dict(c, entity=_strip_period_words(c["heading"])) for c in cells])
    check(f"TSM live: current (846,764,746) vs prior (628,052,531) ({cur and cur['value']}, {prev and prev['value']})",
          cur["value"] == "(846,764,746)" and prev and prev["value"] == "(628,052,531)")


