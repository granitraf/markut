def _cash_block(t):
    return t[t.index("-- Cash flow summary --"):t.index("-- Lease liabilities")]


# ---------------------------------------------------------------- (1) cash-flow wording
def test_cash_flow_rows_in_every_wording(monkeypatch):
    a = _cash_block(_core(monkeypatch, AAPL_CF))
    check(f"AAPL-shaped: 'Cash generated by operating activities' and 'Payments for acquisition of property…' ({a[:300]!r})",
          "116,996" in a and "(6,799)" in a)
    t = _cash_block(_core(monkeypatch, TSM_CF, form="6-K"))
    check(f"TSM-shaped (IFRS): 'Net cash generated by…' and capex under 'Acquisitions of:' ({t[:300]!r})",
          "1,482,341,242" in t and "(846,764,746)" in t)
    u = _cash_block(_core(monkeypatch, US_CF))
    check("synthetic US filer: 'provided by' / 'Purchases of property' still work", "250,000" in u and "(120,000)" in u)


def test_free_cash_flow_from_the_filing(monkeypatch):
    t = _core(monkeypatch, AAPL_CF)
    d = [l for l in t.splitlines() if "DERIVED Free cash flow" in l]
    check(f"AAPL-shaped: free cash flow computed from the filed rows, inputs shown ({d})",
          d and "110,197" in d[0] and "116,996" in d[0] and "6,799" in d[0])
    t2 = _core(monkeypatch, TSM_CF, form="6-K")
    check("TSM-shaped: the same for an IFRS statement", any("DERIVED Free cash flow" in l and "635,576,496" in l for l in t2.splitlines()))


